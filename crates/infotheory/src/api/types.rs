impl ParticleSpec {
    /// Validate all fields, returning an error message on failure.
    pub fn validate(&self) -> InfotheoryResult<()> {
        if self.num_particles == 0 {
            return Err(InfotheoryError::invalid_backend_config(
                "num_particles must be > 0",
            ));
        }
        if self.context_window == 0 {
            return Err(InfotheoryError::invalid_backend_config(
                "context_window must be > 0",
            ));
        }
        if self.unroll_steps == 0 {
            return Err(InfotheoryError::invalid_backend_config(
                "unroll_steps must be > 0",
            ));
        }
        if self.num_cells == 0 {
            return Err(InfotheoryError::invalid_backend_config(
                "num_cells must be > 0",
            ));
        }
        if self.cell_dim == 0 {
            return Err(InfotheoryError::invalid_backend_config(
                "cell_dim must be > 0",
            ));
        }
        if self.num_rules == 0 {
            return Err(InfotheoryError::invalid_backend_config(
                "num_rules must be > 0",
            ));
        }
        if self.selector_hidden == 0 {
            return Err(InfotheoryError::invalid_backend_config(
                "selector_hidden must be > 0",
            ));
        }
        if self.rule_hidden == 0 {
            return Err(InfotheoryError::invalid_backend_config(
                "rule_hidden must be > 0",
            ));
        }
        if !self.learning_rate_readout.is_finite() || self.learning_rate_readout < 0.0 {
            return Err(InfotheoryError::invalid_backend_config(
                "learning_rate_readout must be finite and non-negative",
            ));
        }
        if !self.learning_rate_selector.is_finite() || self.learning_rate_selector < 0.0 {
            return Err(InfotheoryError::invalid_backend_config(
                "learning_rate_selector must be finite and non-negative",
            ));
        }
        if !self.learning_rate_rule.is_finite() || self.learning_rate_rule < 0.0 {
            return Err(InfotheoryError::invalid_backend_config(
                "learning_rate_rule must be finite and non-negative",
            ));
        }
        if !self.noise_scale.is_finite() || self.noise_scale < 0.0 {
            return Err(InfotheoryError::invalid_backend_config(
                "noise_scale must be finite and non-negative",
            ));
        }
        if !self.optimizer_momentum.is_finite()
            || self.optimizer_momentum < 0.0
            || self.optimizer_momentum >= 1.0
        {
            return Err(InfotheoryError::invalid_backend_config(
                "optimizer_momentum must be finite and in [0, 1)",
            ));
        }
        if self.bptt_depth == 0 {
            return Err(InfotheoryError::invalid_backend_config(
                "bptt_depth must be > 0",
            ));
        }
        if !(self.resample_threshold > 0.0 && self.resample_threshold <= 1.0) {
            return Err(InfotheoryError::invalid_backend_config(
                "resample_threshold must be in (0, 1]",
            ));
        }
        if !(self.mutate_fraction >= 0.0 && self.mutate_fraction <= 1.0) {
            return Err(InfotheoryError::invalid_backend_config(
                "mutate_fraction must be in [0, 1]",
            ));
        }
        if !(self.min_prob > 0.0 && self.min_prob < 0.5) {
            return Err(InfotheoryError::invalid_backend_config(
                "min_prob must be in (0, 0.5)",
            ));
        }
        Ok(())
    }
}

