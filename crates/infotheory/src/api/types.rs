impl RateBackend {
    /// Returns the current build's implicit default rate backend.
    pub fn try_default() -> InfotheoryResult<Self> {
        crate::runtime::first_enabled_default_rate_backend_spec().ok_or_else(|| {
            let mut requested = Vec::new();
            for descriptor in crate::runtime::RATE_BACKEND_REGISTRY {
                if let Some(feature) = descriptor.feature
                    && !requested.contains(&feature)
                {
                    requested.push(feature);
                }
            }
            InfotheoryError::unsupported(format!(
                "no default rate backend is available in this build; enable one of: {}",
                requested.join(", ")
            ))
        })
    }

    /// Stable internal backend identity.
    pub(crate) fn kind(&self) -> crate::runtime::RateBackendKind {
        match self {
            RateBackend::RosaPlus => crate::runtime::RateBackendKind::RosaPlus,
            RateBackend::Match { .. } => crate::runtime::RateBackendKind::Match,
            RateBackend::SparseMatch { .. } => crate::runtime::RateBackendKind::SparseMatch,
            RateBackend::Ppmd { .. } => crate::runtime::RateBackendKind::Ppmd,
            RateBackend::Sequitur { .. } => crate::runtime::RateBackendKind::Sequitur,
            #[cfg(feature = "backend-mamba")]
            RateBackend::MambaMethod { .. } => crate::runtime::RateBackendKind::Mamba,
            #[cfg(feature = "backend-rwkv")]
            RateBackend::Rwkv7Method { .. } => crate::runtime::RateBackendKind::Rwkv7,
            RateBackend::Zpaq { .. } => crate::runtime::RateBackendKind::Zpaq,
            RateBackend::Mixture { .. } => crate::runtime::RateBackendKind::Mixture,
            RateBackend::Particle { .. } => crate::runtime::RateBackendKind::Particle,
            RateBackend::Calibrated { .. } => crate::runtime::RateBackendKind::Calibrated,
            RateBackend::Ctw { .. } => crate::runtime::RateBackendKind::Ctw,
            RateBackend::FacCtw { .. } => crate::runtime::RateBackendKind::FacCtw,
        }
    }

    pub(crate) fn descriptor(
        &self,
    ) -> Result<&'static crate::runtime::RateBackendDescriptor, String> {
        crate::runtime::describe_rate_backend_kind(self.kind())
    }

    /// Validate and canonicalize this backend in the provided compilation environment.
    pub fn validate_in(
        &self,
        env: &crate::spec::SpecEnvironment,
    ) -> crate::spec::SpecResult<crate::spec::ValidatedRateBackend> {
        crate::spec::core::validate_rate_backend_in(self, env)
    }

    /// Validate and canonicalize this backend using the default environment.
    pub fn validate(&self) -> crate::spec::SpecResult<crate::spec::ValidatedRateBackend> {
        self.validate_in(&crate::spec::SpecEnvironment::default())
    }

    /// Validate and compile this backend in the provided compilation environment.
    pub fn compile_in(
        &self,
        env: &crate::spec::SpecEnvironment,
    ) -> crate::spec::SpecResult<crate::spec::CompiledRateBackend> {
        self.validate_in(env)?.compile()
    }

    /// Validate and compile this backend using the default environment.
    pub fn compile(&self) -> crate::spec::SpecResult<crate::spec::CompiledRateBackend> {
        self.validate()?.compile()
    }
}

impl CompressionBackend {
    /// Returns the current build's implicit default compression backend.
    pub fn try_default() -> InfotheoryResult<Self> {
        if crate::runtime::COMPRESSION_BACKEND_REGISTRY
            .iter()
            .any(|descriptor| {
                descriptor.enabled
                    && descriptor.kind == crate::runtime::CompressionBackendKind::Zpaq
            })
        {
            return Ok(CompressionBackend::Zpaq {
                method: ZpaqMethodSpec::literal("5"),
            });
        }

        Ok(CompressionBackend::Rate {
            rate_backend: RateBackend::try_default()?,
            coder: crate::coders::CoderType::AC,
            framing: crate::compression::FramingMode::Raw,
        })
    }

    /// Stable internal backend identity.
    pub(crate) fn kind(&self) -> crate::runtime::CompressionBackendKind {
        match self {
            CompressionBackend::Zpaq { .. } => crate::runtime::CompressionBackendKind::Zpaq,
            #[cfg(feature = "backend-rwkv")]
            CompressionBackend::Rwkv7 { .. } => crate::runtime::CompressionBackendKind::Rwkv7,
            CompressionBackend::Rate { coder, .. } => match coder {
                crate::coders::CoderType::AC => crate::runtime::CompressionBackendKind::RateAc,
                crate::coders::CoderType::RANS => crate::runtime::CompressionBackendKind::RateRans,
            },
        }
    }

    /// Canonical registry descriptor for this compression backend.
    pub(crate) fn descriptor(
        &self,
    ) -> Result<&'static crate::runtime::CompressionBackendDescriptor, String> {
        crate::runtime::describe_compression_backend_kind(self.kind())
    }

    /// Validate and canonicalize this backend in the provided compilation environment.
    pub fn validate_in(
        &self,
        env: &crate::spec::SpecEnvironment,
    ) -> crate::spec::SpecResult<crate::spec::ValidatedCompressionBackend> {
        crate::spec::core::validate_compression_backend_in(self, env)
    }

    /// Validate and canonicalize this backend using the default environment.
    pub fn validate(&self) -> crate::spec::SpecResult<crate::spec::ValidatedCompressionBackend> {
        self.validate_in(&crate::spec::SpecEnvironment::default())
    }

    /// Validate and compile this backend in the provided compilation environment.
    pub fn compile_in(
        &self,
        env: &crate::spec::SpecEnvironment,
    ) -> crate::spec::SpecResult<crate::spec::CompiledCompressionBackend> {
        self.validate_in(env)?.compile()
    }

    /// Validate and compile this backend using the default environment.
    pub fn compile(&self) -> crate::spec::SpecResult<crate::spec::CompiledCompressionBackend> {
        self.validate()?.compile()
    }
}
/// Parse a mixture kind name with the shared alias table used across CLI, Python, and WASM.
pub fn parse_mixture_kind_name(kind: &str) -> Result<MixtureKind, String> {
    match kind.trim().to_ascii_lowercase().as_str() {
        "bayes" => Ok(MixtureKind::Bayes),
        "fading-bayes" => Ok(MixtureKind::FadingBayes),
        "switching" => Ok(MixtureKind::Switching),
        "convex" => Ok(MixtureKind::Convex),
        "mdl" => Ok(MixtureKind::Mdl),
        "neural" => Ok(MixtureKind::Neural),
        other => Err(format!("unknown mixture kind '{other}'")),
    }
}

/// Parse a mixture schedule mode with the shared alias table used across CLI, Python, and WASM.
pub fn parse_mixture_schedule_name(schedule: &str) -> Result<MixtureScheduleMode, String> {
    match schedule.trim().to_ascii_lowercase().as_str() {
        "" | "default" => Ok(MixtureScheduleMode::Default),
        "theorem" => Ok(MixtureScheduleMode::Theorem),
        other => Err(format!("unknown mixture schedule '{other}'")),
    }
}

impl MixtureSpec {
    /// Build a mixture specification from kind and expert list.
    pub fn new(kind: MixtureKind, experts: Vec<MixtureExpertSpec>) -> Self {
        Self {
            kind,
            schedule: MixtureScheduleMode::Default,
            alpha: 0.01,
            decay: None,
            experts,
        }
    }

    /// Set the schedule family.
    pub fn with_schedule(mut self, schedule: MixtureScheduleMode) -> Self {
        self.schedule = schedule;
        self
    }

    /// Set the family-specific alpha parameter.
    pub fn with_alpha(mut self, alpha: f64) -> Self {
        self.alpha = alpha;
        self
    }

    /// Set fading decay factor.
    pub fn with_decay(mut self, decay: f64) -> Self {
        self.decay = Some(decay);
        self
    }

    /// Validate the mixture configuration before building runtime state.
    pub fn validate(&self) -> InfotheoryResult<()> {
        validate_mixture_spec_with_depth(self, MAX_MIXTURE_NESTING)
            .map_err(InfotheoryError::invalid_backend_config)
    }

    /// Convert to executable expert configs for runtime mixture evaluation.
    pub fn build_experts(&self) -> Vec<crate::mixture::ExpertConfig> {
        self.experts
            .iter()
            .map(|spec| {
                crate::mixture::ExpertConfig::from_rate_backend(
                    spec.name.clone(),
                    spec.log_prior,
                    spec.backend.clone(),
                    spec.max_order,
                )
            })
            .collect()
    }
}

fn validate_mixture_spec_with_depth(spec: &MixtureSpec, depth: usize) -> Result<(), String> {
    if depth == 0 {
        return Err("mixture spec nesting too deep".to_string());
    }
    validate_mixture_spec_shallow(spec)?;
    for (index, expert) in spec.experts.iter().enumerate() {
        validate_rate_backend_with_depth(&expert.backend, depth - 1).map_err(|err| {
            if let Some(name) = expert.name.as_deref() {
                format!("mixture expert '{name}' invalid: {err}")
            } else {
                format!("mixture expert #{} invalid: {err}", index + 1)
            }
        })?;
    }
    Ok(())
}

fn validate_mixture_spec_shallow(spec: &MixtureSpec) -> Result<(), String> {
    if spec.experts.is_empty() {
        return Err("mixture spec must include at least one expert".to_string());
    }
    if !spec.alpha.is_finite() {
        return Err("mixture alpha must be finite".to_string());
    }
    if spec
        .experts
        .iter()
        .any(|expert| !expert.log_prior.is_finite())
    {
        return Err("mixture expert log_prior must be finite".to_string());
    }
    if let Some(decay) = spec.decay {
        if !decay.is_finite() || !(decay > 0.0 && decay < 1.0) {
            return Err("mixture decay must be in (0, 1)".to_string());
        }
    }
    if matches!(spec.kind, MixtureKind::FadingBayes) && spec.decay.is_none() {
        return Err("fading Bayes mixture requires decay".to_string());
    }
    if spec.schedule != MixtureScheduleMode::Default
        && !matches!(spec.kind, MixtureKind::Switching | MixtureKind::Convex)
    {
        return Err(
            "mixture schedule is only supported for switching and convex mixtures".to_string(),
        );
    }
    match (spec.kind, spec.schedule) {
        (MixtureKind::Switching, MixtureScheduleMode::Default) => {
            if !(0.0..=1.0).contains(&spec.alpha) {
                return Err("switching mixture alpha must be in [0, 1]".to_string());
            }
        }
        (MixtureKind::Convex, MixtureScheduleMode::Default)
        | (MixtureKind::Neural, MixtureScheduleMode::Default) => {
            if spec.alpha <= 0.0 {
                return Err("mixture alpha must be > 0".to_string());
            }
        }
        (MixtureKind::Neural, MixtureScheduleMode::Theorem) => unreachable!(),
        _ => {}
    }
    Ok(())
}

fn validate_rate_backend_with_depth(backend: &RateBackend, depth: usize) -> Result<(), String> {
    let descriptor = crate::runtime::try_describe_rate_backend(backend)
        .map_err(|err| format!("{err} (while validating rate backend)"))?;
    if !descriptor.enabled {
        let Some(feature) = descriptor.feature else {
            return Err(format!(
                "internal backend registry mismatch: disabled backend '{}' is missing required feature metadata",
                descriptor.canonical
            ));
        };
        return Err(format!(
            "backend '{}' requires infotheory feature '{}'",
            descriptor.canonical, feature
        ));
    }
    match backend {
        RateBackend::Sequitur { context_bytes } => {
            if *context_bytes < 2 {
                Err("sequitur context_bytes must be >= 2".to_string())
            } else {
                Ok(())
            }
        }
        RateBackend::Mixture { spec } => validate_mixture_spec_with_depth(spec.as_ref(), depth),
        RateBackend::Particle { spec } => spec.validate().map_err(|err| err.to_string()),
        RateBackend::Calibrated { spec } => {
            if depth == 0 {
                return Err("calibrated spec nesting too deep".to_string());
            }
            validate_rate_backend_with_depth(&spec.base, depth - 1)
                .map_err(|err| format!("calibrated base invalid: {err}"))
        }
        _ => Ok(()),
    }
}

/// Validate a rate backend, including nested mixture/calibrated subgraphs.
pub fn validate_rate_backend(backend: &RateBackend) -> InfotheoryResult<()> {
    validate_rate_backend_with_depth(backend, MAX_MIXTURE_NESTING)
        .map_err(InfotheoryError::invalid_backend_config)
}

/// Validate a compression backend, including nested rate-backed compressors.
pub fn validate_compression_backend(backend: &CompressionBackend) -> InfotheoryResult<()> {
    let descriptor = crate::runtime::try_describe_compression_backend(backend)
        .map_err(InfotheoryError::invalid_backend_config)?;
    if !descriptor.enabled {
        let Some(feature) = descriptor.feature else {
            return Err(InfotheoryError::invalid_backend_config(format!(
                "internal backend registry mismatch: disabled compression backend '{}' is missing required feature metadata",
                descriptor.canonical
            )));
        };
        return Err(InfotheoryError::invalid_backend_config(format!(
            "compression backend '{}' requires infotheory feature '{}'",
            descriptor.canonical, feature
        )));
    }
    if let CompressionBackend::Rate { rate_backend, .. } = backend {
        validate_rate_backend(rate_backend).map_err(|err| {
            InfotheoryError::invalid_backend_config(format!(
                "rate-coded compression backend invalid: {err}"
            ))
        })?;
    }
    Ok(())
}

